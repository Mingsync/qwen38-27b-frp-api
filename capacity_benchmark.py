#!/usr/bin/env python3
"""Probe actual generation overlap, retrieval and GPU/cache pressure.

Uses synthetic prompt cases generated by generate_capacity_prompts.py.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import math
from pathlib import Path
import re
import subprocess
import threading
import time
import urllib.request

from benchmark import consume_sse, percentile

METRIC_PATTERN = re.compile(
    r'^(vllm:(?:num_requests_running|num_requests_waiting|kv_cache_usage_perc|'
    r'gpu_cache_usage_perc|num_preemptions_total))(?:\{[^}]*\})?\s+([0-9.eE+\-]+)$')
PROFILE_KEYS = ['MAX_MODEL_LEN', 'MAX_NUM_SEQS', 'MAX_NUM_BATCHED_TOKENS',
                'GPU_MEMORY_UTILIZATION', 'MAX_NUM_QUEUED_REQS', 'EAGER',
                'PREFIX_CACHING', 'KV_CACHE_DTYPE', 'OMP_NUM_THREADS']


def parse_metrics(text):
    values = {}
    for line in text.splitlines():
        match = METRIC_PATTERN.match(line)
        if match:
            name, raw = match.groups()
            value = float(raw)
            if math.isfinite(value):
                values[name] = values.get(name, 0) + value
    return values


def generation_overlap(results):
    events = []
    for result in results:
        if 'error' not in result:
            events.extend([(result['first_answer_at'], 1), (result['finished_at'], -1)])
    active = peak = 0
    for _, change in sorted(events):
        active += change
        peak = max(peak, active)
    return peak


def markers_in_order(content, markers):
    positions = [content.find(marker) for marker in markers]
    return all(position >= 0 for position in positions) and positions == sorted(positions)


def read_profile(path):
    values = {}
    for line in path.read_text().splitlines():
        name, separator, value = line.partition('=')
        if separator and name in PROFILE_KEYS:
            values[name] = value
    return values


def monitor(base, key, stop, samples, errors):
    while not stop.is_set():
        sample = {'time': time.perf_counter()}
        try:
            request = urllib.request.Request(base.removesuffix('/v1') + '/metrics',
                                             headers={'Authorization': 'Bearer ' + key})
            with urllib.request.urlopen(request, timeout=3) as response:
                sample['metrics'] = parse_metrics(response.read().decode())
            raw = subprocess.check_output(
                ['nvidia-smi', '--query-gpu=memory.used,temperature.gpu',
                 '--format=csv,noheader,nounits'], text=True, timeout=5)
            sample['gpus'] = [[float(value.strip()) for value in row.split(',')]
                              for row in raw.splitlines()]
        except Exception as error:
            errors.append(type(error).__name__)
        samples.append(sample)
        stop.wait(0.5)


def summarize_telemetry(samples):
    output = {}
    names = {
        'peak_running': 'vllm:num_requests_running',
        'peak_waiting': 'vllm:num_requests_waiting',
        'peak_kv_usage_fraction': 'vllm:kv_cache_usage_perc',
    }
    for label, metric in names.items():
        values = [sample['metrics'][metric] for sample in samples
                  if metric in sample.get('metrics', {})]
        output[label] = max(values) if values else None
    if output['peak_kv_usage_fraction'] is None:
        values = [sample['metrics']['vllm:gpu_cache_usage_perc'] for sample in samples
                  if 'vllm:gpu_cache_usage_perc' in sample.get('metrics', {})]
        output['peak_kv_usage_fraction'] = max(values) if values else None
    counts = [sample['metrics']['vllm:num_preemptions_total'] for sample in samples
              if 'vllm:num_preemptions_total' in sample.get('metrics', {})]
    reset = any(current < previous for previous, current in zip(counts, counts[1:]))
    output['preemption_counter_reset'] = reset
    output['preemptions_delta'] = max(counts) - counts[0] if counts and not reset else None
    gpu_samples = [sample['gpus'] for sample in samples if 'gpus' in sample]
    if gpu_samples:
        output['peak_gpu_memory_mib'] = [max(sample[index][0] for sample in gpu_samples)
                                         for index in range(len(gpu_samples[0]))]
        output['peak_gpu_temperature_c'] = [max(sample[index][1] for sample in gpu_samples)
                                            for index in range(len(gpu_samples[0]))]
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--base-url', required=True)
    parser.add_argument('--key-file', type=Path, required=True)
    parser.add_argument('--prompts', type=Path, required=True)
    parser.add_argument('--case', type=int, required=True)
    parser.add_argument('--concurrency', type=int, required=True)
    parser.add_argument('--requests', type=int)
    parser.add_argument('--max-tokens', type=int, default=256)
    parser.add_argument('--force-length', action='store_true')
    parser.add_argument('--deadline', type=int, default=1800)
    parser.add_argument('--profile-env', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    count = args.concurrency if args.requests is None else args.requests
    if not 1 <= args.concurrency <= 256 or count < args.concurrency:
        parser.error('Use 1..256 clients and at least one full concurrency wave')
    if min(args.max_tokens, args.deadline) < 1:
        parser.error('Output and deadline must be positive')
    cases = [json.loads(line) for line in args.prompts.read_text().splitlines()]
    case = next((case for case in cases if case['context'] == args.case), None)
    if case is None:
        parser.error('Requested case is absent from the prompt file')
    key = args.key_file.read_text().strip()
    base = args.base_url.rstrip('/')
    body = {'model': 'qwen3.8-27b', 'messages': case['messages'],
            'max_tokens': args.max_tokens, 'temperature': 0,
            'chat_template_kwargs': {'enable_thinking': False},
            'stream': True, 'stream_options': {'include_usage': True}}
    if args.force_length:
        body.update(min_tokens=args.max_tokens, ignore_eos=True)
    encoded = json.dumps(body).encode()
    samples, monitoring_errors = [], []
    stop = threading.Event()
    sampler = threading.Thread(target=monitor, args=(base, key, stop, samples, monitoring_errors),
                               daemon=True)
    sampler.start()
    time.sleep(1)
    wave = threading.Barrier(args.concurrency)

    def request(index):
        started = time.perf_counter()
        try:
            if index < args.concurrency:
                wave.wait(timeout=60)
            started = time.perf_counter()
            request = urllib.request.Request(base + '/chat/completions', data=encoded,
                headers={'Content-Type': 'application/json', 'Authorization': 'Bearer ' + key})
            with urllib.request.urlopen(request, timeout=60) as response:
                result = consume_sse(response, started, capture_content=True,
                                     total_timeout=args.deadline)
            content = result.pop('content')
            result.update(first_answer_at=started + result['ttft_seconds'],
                          finished_at=started + result['elapsed_seconds'],
                          marker_check=markers_in_order(content, case['expected_markers']),
                          answer_excerpt=content[:160])
            return result
        except Exception as error:
            return {'error': type(error).__name__, 'status': getattr(error, 'code', None),
                    'elapsed_seconds': time.perf_counter() - started}

    started = time.perf_counter()
    try:
        with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
            results = list(pool.map(request, range(count)))
        finished = time.perf_counter()
        # Let the API exporter publish the final engine counters after the last SSE.
        stop.wait(1)
    finally:
        stop.set()
        sampler.join(timeout=10)
    elapsed = finished - started
    passed = [result for result in results if 'error' not in result]
    summary = {'case_context': args.case, 'prompt_tokens_expected': case['prompt_tokens'],
               'concurrency': args.concurrency, 'requests': count, 'successful': len(passed),
               'failed': count - len(passed), 'wall_seconds': elapsed,
               'output_budget': args.max_tokens, 'force_length': args.force_length,
               'max_generation_overlap': generation_overlap(results),
               'marker_checks_passed': sum(result['marker_check'] for result in passed),
               'telemetry': summarize_telemetry(samples),
               'monitoring_errors': sorted(set(monitoring_errors)), 'results': results}
    if args.profile_env:
        summary['server_profile'] = read_profile(args.profile_env)
    if passed:
        for field in ['ttft_seconds', 'elapsed_seconds']:
            values = [result[field] for result in passed]
            summary[field] = {'p50': percentile(values, 0.5), 'p95': percentile(values, 0.95)}
        tokens = [result['completion_tokens'] for result in passed]
        summary['aggregate_output_tokens_per_second'] = None if None in tokens else sum(tokens) / elapsed
        summary['prompt_tokens_observed'] = sorted(set(result['prompt_tokens'] for result in passed))
    args.output.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({key: value for key, value in summary.items() if key != 'results'}, ensure_ascii=False),
          flush=True)
    raise SystemExit(1 if len(passed) != count else 0)


if __name__ == '__main__':
    main()
